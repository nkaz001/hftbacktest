def run_backtest(
    symbol: str,
    data_files: list,
    snapshot_file: str,
    config_file: str,
    output_dir: Path,
    tick_size: float,
    lot_size: float,
) -> bool:
    """Run the Rust backtest binary."""

    cmd = [
        str(BACKTEST_BINARY),
        "--config", config_file,
        "--output", str(output_dir),
        "--tick-size", str(tick_size),
        "--lot-size", str(lot_size),
    ]

    # Add data files
    for data_file in data_files:
        cmd.extend(["--data", data_file])

    # Add snapshot if available
    if snapshot_file:
        cmd.extend(["--snapshot", snapshot_file])

    print(f"\n{'='*60}")
    print(f"Running backtest for {symbol}")
    print(f"{'='*60}")
    print(f"Data files: {len(data_files)}")
    print(f"Command: {' '.join(cmd[:6])}...")
    print()

    try:
        result = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            timeout=600,  # 10 minute timeout
        )

        print(result.stdout)

        if result.returncode != 0:
            print(f"ERROR: Backtest failed with code {result.returncode}")
            print(result.stderr)
            return False

        return True

    except subprocess.TimeoutExpired:
        print("ERROR: Backtest timed out")
        return False
    except Exception as e:
        print(f"ERROR: {e}")
        return False


