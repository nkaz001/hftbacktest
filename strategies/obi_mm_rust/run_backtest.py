def get_date_range(start_date: str, end_date: str = None, days: int = None) -> list:
    """Generate list of dates for backtest."""
    start = datetime.strptime(start_date, "%Y-%m-%d")

    if end_date:
        end = datetime.strptime(end_date, "%Y-%m-%d")
    elif days:
        end = start + timedelta(days=days - 1)
    else:
        end = start

    dates = []
    current = start
    while current <= end:
        dates.append(current.strftime("%Y%m%d"))
        current += timedelta(days=1)

    return dates


def find_data_files(symbol: str, dates: list) -> tuple:
    """Find data files for given symbol and dates."""
    data_files = []
    snapshot_file = None

    for date in dates:
        data_file = DATA_DIR / f"{symbol}_{date}.npz"
        if data_file.exists():
            data_files.append(str(data_file))
            if snapshot_file is None:
                # Use first date's snapshot
                snap = DATA_DIR / f"{symbol}_{date}_last.npz"
                if snap.exists():
                    snapshot_file = str(snap)

    return data_files, snapshot_file


